/** Refusal `r` as the player reads it. */
export const refusalText = (r: RefusalWhy): string =>
  (TEXT[r.code] as (r: RefusalWhy) => string)(r);

/** A refusal as a panel gets it: a core code, or a sentence the UI made itself (a wait note). */
export type Refused = Refusal | { ok: false; reason: string };

/** Refused `r` as the player reads it. */
export const refusedText = (r: Refused): string => ('reason' in r ? r.reason : refusalText(r));

/** A lock's words, or null when nothing is in the way. */
export const lockText = (r: RefusalWhy | null): string | null => (r ? refusalText(r) : null);
